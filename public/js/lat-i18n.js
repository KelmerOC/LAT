  const listeners = [];

  function getSavedLang() {
    const serverExplicit = document.documentElement.getAttribute('data-server-locale');
    if (serverExplicit && DICT[serverExplicit]) {
      return serverExplicit;
    }
    try {
      const saved = localStorage.getItem('lat_lang');
      if (saved && DICT[saved]) return saved;
    } catch (_) {}
    const htmlLang = (document.documentElement.lang || 'es').slice(0, 2).toLowerCase();
    return DICT[htmlLang] ? htmlLang : 'es';
  }

  function t(key, vars) {
    const lang = getSavedLang();
    let str = (DICT[lang] && DICT[lang][key]) || DICT.es[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
      });
    }
    return str;
  }

  function applyTranslations(lang) {
    const valid = DICT[lang] ? lang : 'es';
    const map = DICT[valid];

    document.documentElement.lang = valid;
    if (document.documentElement.hasAttribute('data-server-locale')) {
      document.documentElement.setAttribute('data-server-locale', valid);
    }
    try {
      localStorage.setItem('lat_lang', valid);
    } catch (_) {}

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const val = map[key] || DICT.es[key];
      if (val) {
        el.textContent = val;
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = map[key] || DICT.es[key];
      if (val) {
        el.setAttribute('placeholder', val);
      }
    });

    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      const key = el.getAttribute('data-i18n-aria');
      const val = map[key] || DICT.es[key];
      if (val) {
        el.setAttribute('aria-label', val);
      }
    });

    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      const val = map[key] || DICT.es[key];
      if (val) {
        el.setAttribute('title', val);
      }
    });

    document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
      const key = el.getAttribute('data-i18n-alt');
      const val = map[key] || DICT.es[key];
      if (val) {
        el.setAttribute('alt', val);
      }
    });

    const titleEl = document.querySelector('[data-title-i18n]');
    const titleKey =
      (document.body && document.body.getAttribute('data-title-i18n')) ||
      document.documentElement.getAttribute('data-title-i18n') ||
      (titleEl && titleEl.getAttribute('data-title-i18n'));
    if (titleKey) {
      const titleVal = map[titleKey] || DICT.es[titleKey];
      if (titleVal) {
        document.title = titleVal;
      }
    }

    const labelDesktop = document.getElementById('lang-current-label');
    if (labelDesktop) labelDesktop.textContent = valid.toUpperCase();

    document.querySelectorAll('.lang-mobile-current').forEach((el) => {
      el.textContent = valid.toUpperCase();
    });

    document.querySelectorAll('.lang-opt').forEach((opt) => {
      const activo = opt.dataset.lang === valid;
      opt.classList.toggle('activo', activo);
      opt.setAttribute('aria-selected', activo ? 'true' : 'false');
    });

    document.querySelectorAll('.btn-lang-choice').forEach((btn) => {
      const activo = btn.dataset.lang === valid;
      btn.classList.toggle('activo', activo);
      btn.setAttribute('aria-pressed', activo ? 'true' : 'false');
    });

    listeners.forEach((fn) => {
      try { fn(valid); } catch (_) {}
    });
  }

  function onChange(fn) {
    if (typeof fn === 'function') {
      listeners.push(fn);
    }
  }

  window.LAT_I18N = {
    dict: DICT,
    t: t,
    getLang: getSavedLang,
    apply: applyTranslations,
    onChange: onChange,
  };
